import SwiftUI

// =============================================================================
//  MapWallpaperLayer —— 子页（非地图）铺的那张横图
// =============================================================================
//
//  从 `MapSpineView.swift` 搬来这里（2026-09-25）：那个文件涨到 1211 行，越过了
//  `lintcfg.py` 的 1200 阈值 —— 按那个阈值的用法是把东西搬出去，而不是把文件加进排除清单。
//  搬的是**一件独立的事**（一张铺底的图），界面一字未改。
//
//  为什么是壁纸图而不是 `TokensPalette.canvas`（用户 2026-09-24：「其他页面的背景全部
//  设为当前桌面的背景」）：iOS 没有读主屏壁纸的公开 API（壁纸归 SpringBoard 管，
//  App 进程拿不到）。能做到的最接近的一版是让用户从相册选一张（见 WallpaperService）。
//
//  ===========================================================================
//  2026-09-27 第二轮：平移**不再要求源图有 5 屏宽**（这是「全是颗粒」的根）
//  ===========================================================================
//  上一版（同一天早些时候）是按用户那句「5 屏显示壁纸连贯的不同位置」做的：一整条横图
//  铺 5 屏宽，开一个屏宽的窗口在上面滑。用户这一轮的反馈是：「现在壁纸是咋设置的，
//  全是颗粒，像素很低」—— 颗粒就是上一版买来的，账写在这里：
//
//    一条横图铺 5 屏宽，源图就得有 5 屏那么宽。这台机器一屏 393pt、3× 屏 →
//    **5895 像素**。而免密钥那两个源最大只有 3840（必应 `_UHD.jpg` 3840×2160、
//    聚焦 `landscapeImage` 3840×2160，见 `WallpaperService`），上一版还更糟：
//    必应当时取的是 1920×1080、聚焦优先取的是 1080×1920 的**竖图** ——
//    分别被拉成 3.07 倍与 5.46 倍，屏幕上就是一层颗粒。
//
//  这一版只动一件事：**平移吃掉图本来就多出来的那部分宽度**，而不是要求它有 5 屏宽。
//  铺满这一屏所需的最小放大是 `max(屏宽 ÷ 图宽, 屏高 ÷ 图高)`；按它铺，图会比一屏
//  宽出一段（或宽不出），那段就是可平移的余量：
//    · 16:9 的源（必应 / 聚焦那种）：余量 ≈ 1161pt ≈ 三屏宽 → 每档平移约一整屏；
//    · 4:3 的源：余量 ≈ 772pt → 每档约 0.65 屏；
//    · 竖图 / 方图：横向没有余量 → 五屏看到同一块（这是几何给的答案，不是这一版挑的）。
//
//  放大倍数因此回到「一屏所需」那一档：16:9 从 0.512 降到 **0.405** pt/px、
//  4:3 从 0.487 降到 **0.289**（分别少放 26% 与 68%）。这就是「清晰」与「图上有不同
//  位置」之间那条线：想再多要平移，就得再放大 —— 而放大是有上限的（源图分辨率说了算）。
//
//  ⚠️ 竖图那条如实留着：它不露底、五屏也仍然成立（同一块），但**没有平移**。
//  用户说「壁纸基本都是横向的」，所以这一版按横向图定。
//
//  调用点只有一个：`MapSpineView.pageDeck` 的最底层（在那五张子页**之下**）。
//  它此前挂在每一张子页的 `.background` 上 —— 那样没法平移（五份图各自独立），
//  而且同一张图要画五遍。搬到六页同屏那一层之后：只画一次、只存一份偏移量。
//  地图那一档铺自己的瓦片（铺满、不透明），所以它把这一层整个盖住 —— 用户说的
//  「地图不需要可跳过」在几何上就是这句话。
struct MapWallpaperLayer: View {
    /// 相册/在线选中的那张（`nil` = 没选 / 点了「不铺」）
    let image: UIImage?
    /// 这一段站在那条横图的哪儿：`0` = 最左（第一屏），`1` = 最右（最后一屏）。
    /// 它是**连续量**（拖动时每帧都在变）—— 见 `HomeMode.wallpaperPosition(_:)`。
    /// 「横图有多长」不在这里写死：它由图自己的宽高比与这一屏的尺寸算出来
    ///（`coverWidth`）—— 于是「能平移多远」永远等于「这张图真的多出来多少」。
    let position: Double

    var body: some View {
        GeometryReader { g in
            let w = max(1, g.size.width)
            let h = max(1, g.size.height)
            //  可平移的总宽 = 铺满这一屏所需的最小宽度（16:9 的图会比屏宽出一大截，
            //  竖图则正好等于屏宽 —— 后面那种平移距离为 0，见文件头）。
            let drawn = Self.coverWidth(of: image, in: CGSize(width: w, height: h))
            let travel = max(0, drawn - w)
            ZStack(alignment: .leading) {
                // 底色兜底：没选图（或点了「不铺」）就铺画布（跟随系统深浅色）。
                TokensPalette.canvas
                if let img = image {
                    //  ⚠️ 2026-09-26（「聚焦那一档时图源点不动」那一轮）留下的三件：
                    //  `.frame(...)` / `.clipped()` / `.allowsHitTesting(false)`。
                    //  这里的两层 `clipped()` 各有各的用：里层把 `.fill` 报出来的
                    //  「填满提案」的溢出裁在横图自己的框里（竖图会报得比框高），
                    //  外层把窗口以外那几屏裁掉。
                    //  ⚠️ 2026-09-27：这一版的 `drawn` 就是**图自己铺满后的宽度**，
                    //  不再是「屏宽 × 5」—— 放大倍数因此回到最小那一档（见文件头）。
                    Image(uiImage: img)
                        .resizable()
                        .aspectRatio(contentMode: .fill)
                        .frame(width: drawn, height: h)
                        .clipped()
                        .offset(x: -CGFloat(min(1, max(0, position))) * travel)
                }
            }
            //  窗口：宽一个屏、高一个屏，锚在左边（`alignment: .leading`）——
            //  横图比窗口宽，锚点决定「0 那一屏看的是哪一段」。
            .frame(width: w, height: h, alignment: .leading)
            .clipped()
        }
        // 铺底图不需要任何一份命中（它是背景装饰，见 `MapSpineView.pageDeck`）。
        .allowsHitTesting(false)
        // 铺到屏顶、屏底（状态栏那一段也铺）——调用点不必再管安全区。
        .ignoresSafeArea()
    }

    /// 这张图按「铺满」放大后会画多宽。
    ///
    /// 就是 `.fill` 的那条算术，只是搬到这里先算出来 —— 因为**平移距离需要它**
    ///（窗口在它上面滑）。`nil`（没选图）当作「正好一屏宽」，于是平移距离为 0，
    /// 画布那一层不会被推走。
    static func coverWidth(of image: UIImage?, in size: CGSize) -> CGFloat {
        guard let img = image, img.size.width > 0, img.size.height > 0 else { return size.width }
        let ar = img.size.width / img.size.height
        return max(size.width, size.height * ar)
    }
}
