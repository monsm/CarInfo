import SwiftUI

// =============================================================================
//  StackSpec —— 「上下叠叠乐」剩下的那点几何
// =============================================================================
//
//  这些数字不是调出来的，是**量出来的**：原型 `design-preview/stack.html` 里
//  每一条都有出处（卡片圆角、内边距、左右外边距、卡片间距）。
//  集中在一处的理由与令牌一样 —— 同一个决定只能做一次。六页各自写一遍，
//  就会出现「出行页间距对、充电页不对」。
//
//  2026-09-25：这里**从「七种叠法的一张表」缩成一个 Card**。
//  缩掉的三样，每一样的服务对象都没了：
//    ① `StackVariant`（七选一）—— 用户 2026-09-24：「叠叠乐只用吸附堆叠，
//       其他都删除」；2026-09-25（第二轮）滚动本身也交回系统，剩下的那一种
//       不再有任何属于自己的行为（它就是「卡片按真实高度排队」= 系统的 `VStack`）。
//       七个 case 的几何（弧度、错位、滚轮角度）连同 `StackMetrics` / `StackKind`
//       一起删除 —— 留着它们就是留一排**没有读者**的旋钮，下一个人读到这里会以为
//       叠法还是可选的。要找回那七种的参数，看删掉它们的那次提交。
//    ② `variantKey` / `chosen` / `remember` —— 它们是「存下来的那一档」。
//       唯一的档位不需要存：UserDefaults 里那个旧键不再被读也不再被写
//       （旧值留在用户设备上，不再有任何影响）。
//    ③ 判定（原来的 `StackMath`：硬限位、连续焦点序号、吸附落点、松手落点）——
//       2026-09-24 删吸附、2026-09-25 把位置与减速曲线交回系统，四件事全归系统。
//
//  留在仓库里的后果与「幽灵功能」一样：下一个读到这里的人会以为滚动还归我们管。
enum StackSpec {

    /// 卡片自己的尺寸与圆角（原型 `.card{padding:17px 18px 16px;border-radius:26px}`）
    enum Card {
        static let radius = CGFloat(26)
        static let padH = CGFloat(18)
        static let padTop = CGFloat(17)
        static let padBottom = CGFloat(16)
        /// 卡片的外边距：屏幕左右各留 18（原型 `.stack{padding:… 18px …}`）
        static let inset = CGFloat(18)
        /// 卡片之间（原型 `.stack{gap:14px}`）。
        ///
        /// 它现在只是 `VStack` 的 `spacing` —— 最小、最原生的一种间距：
        /// 系统自己把卡片一张张排开，我们不参与「谁在哪儿」。
        static let gap = CGFloat(14)
    }

    // 阅读线、消失带、两端留白都不在这里了（2026-09-25 第二轮）：
    //   · 阅读线（曾经的 `dockRatio` / `focusInset`）是「自管滚动」时代的产物 ——
    //     那时容器上沿是一条我们自己画的消失带下沿，卡片要停在那条线下面。
    //     现在容器上沿就是内容区的上沿，卡片从第一张开始排，没有那条线。
    //   · 消失带（`fadeTop` / `fadeBottom`）随遮罩一起删（见 `ArcStack` 头注）。
    //   · 两端留白（内容下沿让开一段，好让末卡停到底）也不需要了：
    //     末端 = 内容底端，就是系统滚动的末端。

    /// 无障碍翻页那一步的弹簧（`ArcStack.step`）。
    /// 手势与惯性都不走它 —— 手势与惯性都是系统滚动自己的。
    /// 刚度 130 / 阻尼 16：被点一下的「滑过去」那一下。
    static let settle = Animation.interpolatingSpring(mass: 1, stiffness: 130, damping: 16)
}
