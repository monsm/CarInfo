import Foundation

// =============================================================================
//  启动围栏 —— 关掉一部分启动代码，用来二分定位「载入不到 10 秒就退」
// =============================================================================
//
//  为什么要有它（用户 2026-09-24：「你试试屏蔽一部分运行代码，我们来一个排查」）：
//  这件事靠读代码已经排了一整轮 —— 死循环 / 强解包 / 下标越界 / 区间构造 /
//  权限键 / 布局回环 / 整数换算，逐条都验过是干净的，而它在真机上依旧每次复现。
//  读不动的时候，唯一还剩下的方法是**实验**：把启动时做的事一组组关掉，
//  看它还在不在。关掉之后不退，凶手就在关掉的那一组里；照旧退，
//  凶手在剩下的那一小块里 —— 两种结果都缩小范围，都不白装。
//
//  这一版（第一次实验）：四个开关**全关**，即「最小启动」——
//  只做「画当前这一档 + 取一次数据」。界面上的差别都写在每个开关下面，
//  免得把「关掉了」看成「修好了」。
//
//  下一版的走法（对半开，一次一个）：
//    ② 只把 `sixPageDeck` 打开 —— 六页同屏是启动时最大的一笔开销
//    ③ 再把 `splash` 打开 —— 启动动画结束时整棵树会重建一次
//    ④ 再把 `mapFetches` 打开
//    ⑤ 最后把 `launchServices` 打开（那一批服务各自有权限与系统回调）
//
//  ⚠️ 它是**临时仪器**，不是特性开关：查完就把本文件与它的四个使用点一起删掉
//  （`delguard.py` 会盯着「删了声明、使用还在」——删的时候它会指出漏了哪一处）。
//  长期留在代码里等于「同一件事有两种运行方式」，那正是这个仓库反复删掉的东西。
enum LaunchFence {

    /// 六页同屏（`MapSpineView.pageDeck`）：关掉之后只建当前那一档，
    /// 其余五档连 body 都不跑（顺带它们的取数也不会跑）。
    /// 界面差别：换档是「直接换」，没有交叉淡出与那点从 96.5% 长出来的实体感。
    static let sixPageDeck = false

    /// 启动时那一批服务：内存监控 / 网络质量 / 离线监听 / 通知授权 /
    /// 远程锁定 / 摇一摇 / 维保与保险提醒 / 专注模式 / 充电状态 / 车牌加密。
    /// 界面差别：不再请求通知权限，摇一摇不锁车，离线提示不出现。
    static let launchServices = false

    /// 启动动画：关掉之后直接进主界面。
    /// 界面差别：没有开场那 1.5 秒（也少了那一次整棵树重建）。
    static let splash = false

    /// 地图页自己的取数（车况 / 天气 / 充电桩搜索）。
    /// 界面差别：地图上不再有车的位置与天气图层；数据仍由冷启动那次取数补上。
    static let mapFetches = false

    /// 这一版装了哪几个开关 —— 写进启动轨迹的第一行。
    /// 轨迹会被复制出来贴给人看，没有这一行，「这一次是哪个实验」就说不清。
    static var summary: String {
        let f: (Bool) -> String = { $0 ? "开" : "关" }
        return "实验 六页[\(f(sixPageDeck))] 服务[\(f(launchServices))] 开场[\(f(splash))] 地图取数[\(f(mapFetches))]"
    }
}
