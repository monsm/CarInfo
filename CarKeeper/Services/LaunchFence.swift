import Foundation

// =============================================================================
//  启动围栏 —— 关掉一部分启动代码，用来二分定位「载入不到 10 秒就退」
// =============================================================================
//
//  为什么要有它（用户 2026-09-24：「你试试屏蔽一部分运行代码，我们来一个排查」）：
//  这件事靠读代码已经排了一整轮 —— 死循环 / 强解包 / 下标越界 / 区间构造 /
//  权限键 / 布局回环 / 整数换算，逐条都验过是干净的，而它在真机上依旧每次复现。
//  读不动的时候，唯一还剩下的方法是**实验**：把启动时做的事一组组关掉，
//  看它还在不在。关掉之后不退，凶手就在关掉的那一组里；照旧退，
//  凶手在剩下的那一小块里 —— 两种结果都缩小范围，都不白装。
//
//  ── 实验记录（写到哪儿了，照实记）──────────────────────────────────────
//
//   ① **最小启动**（四个全关）：跑了一段，用户在这一版上做了好几轮界面。
//   ② 2026-09-25 用户回执：「先正常启动试一次」→ 这一版**四个全开**（正式形态）。
//      先回答最直接的那个问题：在现在这棵树上，正常的启动路径还会不会退。
//
//  如果②又退，按下面这个顺序**一次往回关一个**（先关最大的那一笔）：
//    ③ 关 `sixPageDeck` —— 六页同屏是启动时最大的一笔开销
//    ④ 关 `splash` —— 启动动画结束时整棵树会重建一次
//    ⑤ 关 `mapFetches`
//    ⑥ 关 `launchServices`（那一批服务各自有权限与系统回调）—— 回到①
//
//  ⚠️ 它是**临时仪器**，不是特性开关：查完就把本文件与它的四个使用点一起删掉
//  （`delguard.py` 会盯着「删了声明、使用还在」——删的时候它会指出漏了哪一处）。
//  长期留在代码里等于「同一件事有两种运行方式」，那正是这个仓库反复删掉的东西。
enum LaunchFence {

    /// 六页同屏（`MapSpineView.pageDeck`）：关掉之后只建当前那一档，
    /// 其余五档连 body 都不跑（顺带它们的取数也不会跑）。
    /// 界面差别：换档是「直接换」，没有交叉淡出与那点从 96.5% 长出来的实体感。
    ///
    /// ⚠️ 它是这一组里最贵的一个：全开时六张完整界面同时在树上 —— 轨迹里那笔
    /// 「49 MB → 1.7 GB 只要四秒」就发生在它身上（见 HANDOFF §18.3）。
    static let sixPageDeck = true

    /// 启动时那一批服务：内存监控 / 通知授权 / 远程锁定 /
    /// 维保与保险提醒 / 充电状态。
    ///（这一行原本还列着「网络质量 / 离线监听 / 车牌加密」——三个都已不在启动期：
    ///  前两个随 2026-09-26 第三十一轮审核改成「谁读谁建」，第三个是删掉的加密初始化。
    ///  与上一行那个教训一样：开关旁边这份清单不会自己跟着变。）
    /// 界面差别：不再请求通知权限，离线提示不出现。
    ///（这一行原本还列着「摇一摇 / 专注模式」—— 那两个功能 2026-09-25 第九轮已整份删除，
    /// 而这段注释是随开关一起写的：删功能时它不会自己跟着变。）
    static let launchServices = true

    /// 启动动画：关掉之后直接进主界面。
    /// 界面差别：没有开场那 1.5 秒（也少了那一次整棵树重建）。
    static let splash = true

    /// 地图页自己的取数（车况 / 天气 / 充电桩搜索）。
    /// 界面差别：地图上不再有车的位置与天气图层；数据仍由冷启动那次取数补上。
    ///
    /// ⚠️ 它管的是**启动时**那一趟（`MapSpineView` 的 `.task`）。之后的自动刷新由
    /// `RefreshLoop` 按节律做，**不在这四个开关里** —— 那个循环第一次取数在 2 秒
    ///（地图页）/ 60 秒（其他档）之后，与「载入不到 10 秒就退」不在同一个时间窗。
    /// 做干净的启动实验时，
    /// 需要连它一起停就调 `RefreshLoop.shared.stop()`（它没有开关，因为它是正式形态的一部分）。
    static let mapFetches = true

    /// 这一版装了哪几个开关 —— 写进启动轨迹的第一行。
    /// 轨迹会被复制出来贴给人看，没有这一行，「这一次是哪个实验」就说不清。
    static var summary: String {
        let f: (Bool) -> String = { $0 ? "开" : "关" }
        return "实验 六页[\(f(sixPageDeck))] 服务[\(f(launchServices))] 开场[\(f(splash))] 地图取数[\(f(mapFetches))]"
    }
}
